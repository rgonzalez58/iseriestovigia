-- Paridad TRANSACCIONES: TMP del SSIS (VIGIA.TMP_TRANSACCIONES) vs carga Python (VIGIA.TMP_TRANSACCIONES_PY).
-- Crear TMP_TRANSACCIONES_PY con la misma estructura y apuntar 'destino' del config.yaml a ella durante la prueba.
-- Tabla grande: conviene acotar por FECHA (p. ej. el último mes) antes de comparar. Esperado: sin filas y conteos iguales.
DECLARE @desde datetime = DATEADD(MONTH, -1, GETDATE());
SELECT TERCERO_TIPIDE_CODIGO, TERCERO_NUMIDE, PRODUCTO_CODIGO, PRODUCTO_NUMERO, TIPTRAN_CODIGO, FECHA, CONSECUTIVO,
       SISGEO_CODIGO, SUCURSAL_CODIGO, VALOR, VALORMONEDAEXTRANJERA, TIPMON_CODIGO, INTERMEDIARIO_CODIGO,
       CODIGOPAISREMITE, REFERENCIA1 FROM VIGIA.TMP_TRANSACCIONES WHERE FECHA >= @desde
EXCEPT
SELECT TERCERO_TIPIDE_CODIGO, TERCERO_NUMIDE, PRODUCTO_CODIGO, PRODUCTO_NUMERO, TIPTRAN_CODIGO, FECHA, CONSECUTIVO,
       SISGEO_CODIGO, SUCURSAL_CODIGO, VALOR, VALORMONEDAEXTRANJERA, TIPMON_CODIGO, INTERMEDIARIO_CODIGO,
       CODIGOPAISREMITE, REFERENCIA1 FROM VIGIA.TMP_TRANSACCIONES_PY WHERE FECHA >= @desde;

SELECT TERCERO_TIPIDE_CODIGO, TERCERO_NUMIDE, PRODUCTO_CODIGO, PRODUCTO_NUMERO, TIPTRAN_CODIGO, FECHA, CONSECUTIVO,
       SISGEO_CODIGO, SUCURSAL_CODIGO, VALOR, VALORMONEDAEXTRANJERA, TIPMON_CODIGO, INTERMEDIARIO_CODIGO,
       CODIGOPAISREMITE, REFERENCIA1 FROM VIGIA.TMP_TRANSACCIONES_PY WHERE FECHA >= @desde
EXCEPT
SELECT TERCERO_TIPIDE_CODIGO, TERCERO_NUMIDE, PRODUCTO_CODIGO, PRODUCTO_NUMERO, TIPTRAN_CODIGO, FECHA, CONSECUTIVO,
       SISGEO_CODIGO, SUCURSAL_CODIGO, VALOR, VALORMONEDAEXTRANJERA, TIPMON_CODIGO, INTERMEDIARIO_CODIGO,
       CODIGOPAISREMITE, REFERENCIA1 FROM VIGIA.TMP_TRANSACCIONES WHERE FECHA >= @desde;

SELECT (SELECT COUNT(*) FROM VIGIA.TMP_TRANSACCIONES WHERE FECHA >= @desde) AS SSIS,
       (SELECT COUNT(*) FROM VIGIA.TMP_TRANSACCIONES_PY WHERE FECHA >= @desde) AS PYTHON;
