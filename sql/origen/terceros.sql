SELECT
    psa065td AS TIPIDE_CODIGO,
    psa065do AS NUMIDE,
    TRIM(psa065nm) AS NOMBRES,
    TRIM(psa065ap) AS APELLIDOS,
    psa065ci AS SISGEO_CODIGO,
    psa065ti AS TIPO,

    NULLIF(NULLIF(TRIM(psa065pf), '0'), '') AS PROFESION_CODIGO,
    NULLIF(NULLIF(TRIM(psa065oc), '0'), '') AS ACTIVIDAD_CODIGO,

    psa065ac AS ACTIVO,
    psa065ps AS PASIVO,
    psa065pt AS PATRIMONIO,
    psa065in AS INGRESOS,
    psa065eg AS EGRESOS,
    psa065ct AS CUPOTOTAL,
    psa065ri AS TIPCAL_CODIGO,

    NULLIF(TRIM(psa065vi), '') AS TIPVIN_CODIGO,
    psa065di AS DIRECCION,
    NULLIF(TRIM(psa065tf), '') AS TELEFONO,
    NULLIF(TRIM(psa065em), '') AS EMAIL,

    psa065fi AS FECHAVINCULACION,
    psa065fa AS FECHAACTUALIZACION,

    NULLIF(NULLIF(TRIM(psa065ej), '0'), '')
        AS FUNCIONARIO_RESPONSABLE,

    NULLIF(NULLIF(TRIM(psa065ae), '0'), '')
        AS CIIU_CODIGO,

    COALESCE(NULLIF(TRIM(psa065pe), ''), 'n') AS PEP,

    NULLIF(TRIM(psa065tp), '') AS TIPPEP_CODIGO,
    NULLIF(TRIM(psa065sg), '') AS SEGMENTO_CODIGO,

    COALESCE(NULLIF(TRIM(psa065su), ''), '1')
        AS SUCURSAL_CODIGO,

    psa065fn AS FECHA_NACIMIENTO,
    psa065ea AS EXENTOANALISIS,

    NULLIF(TRIM(psa065sx), '') AS SEXO,
    psa065es AS ESTADO,
    psa065an AS AUTORIZANOTIFICACION,

    NULLIF(NULLIF(TRIM(psa065nj), '0'), '')
        AS NATURALEZAJURIDICA,

    NULLIF(NULLIF(TRIM(psa065na), '0'), '')
        AS SISGEO_NACIONALIDAD,

    NULLIF(NULLIF(TRIM(psa065pn), '0'), '')
        AS PAIS_NACIMIENTO,

    NULLIF(TRIM(psa065ec), '') AS ESTADOCIVIL_CODIGO,

    psa065nl AS NOMBREEMPRESALABORA,
    psa065dl AS DIRECCIONEMPRESALABORA,
    psa065pa AS LUGAREXPEDICION_CODIGO

FROM gnbweb_db.psa065
WHERE psa065es = 'A'